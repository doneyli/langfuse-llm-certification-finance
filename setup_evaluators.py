#!/usr/bin/env python3
"""
Create Langfuse-managed evaluators + an evaluation rule for production traffic

The offline deployment gate scores experiments in-process (evaluators.py). In
production the same checks can run *inside Langfuse*, on live traffic, with no
cron job:

  regulatory_compliance  code evaluator (Python, BOOLEAN)  prohibited-phrase scan
  completeness           code evaluator (Python, NUMERIC)  length/structure heuristic
  groundedness           LLM-as-a-judge (NUMERIC 0..1)     GROUNDEDNESS_RUBRIC

The code evaluators' source is generated from evaluators.py itself
(``compliance_violations``, ``completeness_score``, ``PROHIBITED_PHRASES``), so
the gate and live monitoring cannot drift apart. Two evaluation rules select
what to score: root observations (``isRootObservation = true``) in the
``production`` environment — every match for the code evaluators, 20% for the
judge to manage cost.

Rules are created **disabled** unless you pass ``--enable``: an enabled rule
starts scoring live traffic (and the judge spends tokens) immediately.

Human step: the groundedness judge uses the project's default evaluation model
(an LLM connection set up in Langfuse → Settings → LLM Connections). See
docs/loop-activation-checklist.md.

Self-hosted: Python code evaluators need the ``aws-lambda`` code-eval dispatcher;
``insecure-local`` runs TypeScript/JavaScript only. Without a dispatcher keep
using monitor_production.py, which runs the same checks from cron.

Usage:
    python setup_evaluators.py --dry-run          # print every payload, create nothing
    python setup_evaluators.py                    # create missing evaluators + disabled rules
    python setup_evaluators.py --enable           # ... and enable the rules
    python setup_evaluators.py --environment prod --judge-sampling 0.1
    python setup_evaluators.py --print-source regulatory_compliance

Idempotent by name: an evaluator or rule whose name already exists is skipped.
"""

import argparse
import inspect
import json
import sys
import urllib.error
import urllib.request

import evaluators as ev
from cert_common import langfuse_creds, paginate_cursor


RULE_PREFIX = "deployment-gate"
CODE_RULE_NAME = f"{RULE_PREFIX}: deterministic checks on production"
JUDGE_RULE_NAME = f"{RULE_PREFIX}: groundedness judge on production"


# --------------- Code evaluator source (generated from evaluators.py) ---------------

_ANSWER_TEXT = '''
def _answer_text(output):
    """The answer string from a root observation's output.

    Agent runs record {"answer": ..., "trajectory": ...}; plain apps a string.
    Anything else is scored as its JSON text.
    """
    if isinstance(output, dict):
        if isinstance(output.get("answer"), str):
            return output["answer"]
        return json.dumps(output)
    if output is None:
        return ""
    if isinstance(output, str):
        try:
            parsed = json.loads(output)
        except ValueError:
            return output
        if isinstance(parsed, dict) and isinstance(parsed.get("answer"), str):
            return parsed["answer"]
        return output
    return json.dumps(output)
'''

_EVALUATE = {
    "regulatory_compliance": '''
def evaluate(ctx):
    text = _answer_text(ctx.observation.output)
    if not text:
        return EvaluationResult(scores=[Score(
            name="regulatory_compliance", value=True, data_type="BOOLEAN",
            comment="No output to check")])
    violations = compliance_violations(text, PROHIBITED_PHRASES)
    return EvaluationResult(scores=[Score(
        name="regulatory_compliance", value=not violations, data_type="BOOLEAN",
        comment=("Violations found: " + ", ".join(violations)) if violations
        else "No prohibited phrases detected")])
''',
    "completeness": '''
def evaluate(ctx):
    text = _answer_text(ctx.observation.output)
    if not text:
        return EvaluationResult(scores=[Score(
            name="completeness", value=0.0, data_type="NUMERIC",
            comment="Empty response")])
    score, comment = completeness_score(text)
    return EvaluationResult(scores=[Score(
        name="completeness", value=score, data_type="NUMERIC", comment=comment)])
''',
}

_HELPERS = {
    "regulatory_compliance": [ev.compliance_violations],
    "completeness": [ev.completeness_score],
}


def code_evaluator_source(name: str) -> str:
    """Python source for one managed code evaluator, built from evaluators.py.

    ``Score`` and ``EvaluationResult`` are provided by the Langfuse runtime
    (see the code-evaluator function contract). Stdlib only, no network.
    """
    parts = [
        f"# Generated by setup_evaluators.py from evaluators.py — do not edit in the UI;\n"
        f"# change evaluators.py and re-run setup_evaluators.py instead.\n"
        f"import json\n",
        f"PROHIBITED_PHRASES = {json.dumps(ev.PROHIBITED_PHRASES)}\n",
        _ANSWER_TEXT,
    ]
    for fn in _HELPERS[name]:
        parts.append("\n" + inspect.getsource(fn))
    parts.append(_EVALUATE[name])
    return "".join(parts)


# --------------- LLM-as-a-judge prompt ---------------

def judge_prompt() -> str:
    """The groundedness rubric as a Langfuse judge prompt.

    The offline judge formats {evidence}/{question}/{output} itself and parses
    JSON. Langfuse's judge returns a structured score, so the managed prompt
    takes the root observation's whole input (question + evidence) and output
    and the scoring formula moves into the output definition.
    """
    return (
        "You are an expert financial auditor evaluating whether an AI "
        "assistant's answer is grounded in the source documents it was given.\n\n"
        "<request>\n{{input}}\n</request>\n\n"
        "<assistant_answer>\n{{output}}\n</assistant_answer>\n\n"
        "The request contains the question and the source documents (an "
        "`evidence` list). Evaluate the answer on two dimensions:\n\n"
        "1. Faithfulness (0.0 - 1.0): Is every claim supported by the source "
        "documents? Penalize hallucinated facts, invented numbers, or statements "
        "not traceable to the evidence.\n"
        "2. Completeness (0.0 - 1.0): Does the answer address the key "
        "information from the source documents that is relevant to the question?\n"
    )


JUDGE_OUTPUT = {
    "dataType": "NUMERIC",
    "minValue": 0,
    "maxValue": 1,
    "scoreValueInstructions": (
        "Return 0.7 * faithfulness + 0.3 * completeness, rounded to 3 decimals "
        "(faithfulness weighs more in finance). If the request has no source "
        "documents, return 1.0 only if the answer makes no factual claims."),
    "scoreReasoningInstructions": (
        "State faithfulness and completeness as numbers, then 1-2 sentences "
        "naming any unsupported claim."),
}


# --------------- Payloads ---------------

def evaluator_payloads() -> list:
    return [
        {"type": "code", "name": "regulatory_compliance",
         "description": "Deployment gate: prohibited financial phrases "
                        "(evaluators.PROHIBITED_PHRASES). true = clean.",
         "sourceCode": code_evaluator_source("regulatory_compliance"),
         "sourceCodeLanguage": "PYTHON"},
        {"type": "code", "name": "completeness",
         "description": "Deployment gate: length/structure heuristic "
                        "(evaluators.completeness_score), 0.2-1.0.",
         "sourceCode": code_evaluator_source("completeness"),
         "sourceCodeLanguage": "PYTHON"},
        {"type": "llm_as_judge", "name": "groundedness",
         "description": "Deployment gate: groundedness vs source evidence "
                        "(evaluators.GROUNDEDNESS_RUBRIC), 0-1.",
         "prompt": judge_prompt(),
         "modelConfig": None,  # the project's default evaluation model
         "variableMapping": [{"variable": "input", "source": "input"},
                             {"variable": "output", "source": "output"}],
         "outputDefinition": JUDGE_OUTPUT},
    ]


def rule_filter(environment: str) -> list:
    return [
        {"type": "boolean", "column": "isRootObservation", "operator": "=",
         "value": True},
        {"type": "stringOptions", "column": "environment", "operator": "any of",
         "value": [environment]},
    ]


def rule_payloads(evaluator_ids: dict, *, environment: str, enable: bool,
                  judge_sampling: float) -> list:
    return [
        {"name": CODE_RULE_NAME, "enabled": enable, "sampling": 1.0,
         "filter": rule_filter(environment),
         "evaluatorAssignments": [
             {"evaluatorId": evaluator_ids["regulatory_compliance"]},
             {"evaluatorId": evaluator_ids["completeness"]}]},
        {"name": JUDGE_RULE_NAME, "enabled": enable, "sampling": judge_sampling,
         "filter": rule_filter(environment),
         "evaluatorAssignments": [{"evaluatorId": evaluator_ids["groundedness"]}]},
    ]


# --------------- API ---------------

def _post(path, body):
    host, auth = langfuse_creds()
    req = urllib.request.Request(
        f"{host}{path}", data=json.dumps(body).encode(), method="POST",
        headers={"Authorization": f"Basic {auth}",
                 "Content-Type": "application/json"})
    return json.loads(urllib.request.urlopen(req).read())


def _existing_by_name(path):
    return {row.get("name"): row for row in paginate_cursor(path)}


# --------------- CLI ---------------

def parse_args(argv=None):
    ap = argparse.ArgumentParser(
        description="Create Langfuse-managed evaluators + rules for production")
    ap.add_argument("--dry-run", action="store_true",
                    help="Print the payloads; create nothing")
    ap.add_argument("--enable", action="store_true",
                    help="Create the rules enabled (default: disabled drafts)")
    ap.add_argument("--environment", default="production",
                    help="Langfuse environment the rules score (default: production)")
    ap.add_argument("--judge-sampling", type=float, default=0.2,
                    help="Fraction of matches the groundedness judge scores "
                         "(default: 0.2)")
    ap.add_argument("--print-source", choices=sorted(_EVALUATE),
                    help="Print one generated code-evaluator source and exit")
    return ap.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    if args.print_source:
        print(code_evaluator_source(args.print_source))
        return 0

    try:
        from dotenv import load_dotenv
        load_dotenv(override=True)
    except ImportError:
        pass

    host, _ = langfuse_creds()
    print("Langfuse managed evaluators", file=sys.stderr)
    print("=" * 50, file=sys.stderr)
    print(f"  Target:      {host}", file=sys.stderr)
    print(f"  Environment: {args.environment}", file=sys.stderr)
    print(f"  Rules:       {'enabled' if args.enable else 'disabled (draft)'}",
          file=sys.stderr)

    if args.dry_run:
        ids = {p["name"]: f"<{p['name']}-id>" for p in evaluator_payloads()}
        print("\n  ** DRY RUN - nothing will be created **\n", file=sys.stderr)
        print(json.dumps({
            "evaluators": evaluator_payloads(),
            "evaluation_rules": rule_payloads(
                ids, environment=args.environment, enable=args.enable,
                judge_sampling=args.judge_sampling),
        }, indent=2))
        return 0

    existing = _existing_by_name("/api/public/v2/evaluators")
    ids = {}
    for payload in evaluator_payloads():
        name = payload["name"]
        if name in existing:
            ids[name] = existing[name]["id"]
            print(f"  [skip] evaluator {name} (exists: {ids[name]})", file=sys.stderr)
            continue
        try:
            created = _post("/api/public/v2/evaluators", payload)
        except urllib.error.HTTPError as e:
            print(f"  [error] evaluator {name}: {e.code} {e.read().decode()}",
                  file=sys.stderr)
            return 1
        ids[name] = created["id"]
        print(f"  [created] evaluator {name} ({payload['type']}, id: {ids[name]})",
              file=sys.stderr)

    rules = _existing_by_name("/api/public/v2/evaluation-rules")
    for payload in rule_payloads(ids, environment=args.environment,
                                 enable=args.enable,
                                 judge_sampling=args.judge_sampling):
        if payload["name"] in rules:
            print(f"  [skip] rule '{payload['name']}' (exists)", file=sys.stderr)
            continue
        try:
            created = _post("/api/public/v2/evaluation-rules", payload)
        except urllib.error.HTTPError as e:
            print(f"  [error] rule '{payload['name']}': {e.code} {e.read().decode()}",
                  file=sys.stderr)
            return 1
        print(f"  [created] rule '{payload['name']}' (id: {created['id']}, "
              f"{'enabled' if payload['enabled'] else 'disabled'})", file=sys.stderr)

    print("\n  Next: add an Alert on regulatory_compliance (see "
          "docs/loop-activation-checklist.md).", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
